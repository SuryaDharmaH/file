-- Bucket publik agar penerima dapat mengunduh melalui tautan.
insert into storage.buckets (id, name, public, file_size_limit)
values ('fileku', 'fileku', true, 52428800)
on conflict (id) do update set public = true, file_size_limit = 52428800;

create table if not exists public.files (
  id bigint generated by default as identity primary key,
  name text not null,
  path text not null unique,
  size bigint not null,
  mime_type text not null default 'application/octet-stream',
  public_url text not null,
  created_at timestamptz not null default now()
);

alter table public.files enable row level security;

drop policy if exists "Anyone can view file records" on public.files;
create policy "Anyone can view file records"
on public.files for select to anon, authenticated using (true);

drop policy if exists "Anyone can add file records" on public.files;
create policy "Anyone can add file records"
on public.files for insert to anon, authenticated
with check (
  char_length(name) between 1 and 255
  and size > 0 and size <= 52428800
  and char_length(path) between 1 and 220
);

drop policy if exists "Public can upload to FileKu bucket" on storage.objects;
create policy "Public can upload to FileKu bucket"
on storage.objects for insert to anon, authenticated
with check (bucket_id = 'fileku');

